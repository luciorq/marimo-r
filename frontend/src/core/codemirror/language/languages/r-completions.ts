/**
 * Check whether the cursor is inside a string or comment in R code.
 *
 * Since R uses StreamLanguage (legacy mode) without a full Lezer tree,
 * we use a simple heuristic: scan backwards from the cursor to detect
 * unmatched quotes or a leading `#` on the current line.
 */
function isInsideStringOrComment(context: CompletionContext): boolean {
  const line = context.state.doc.lineAt(context.pos);
  const textBefore = line.text.slice(0, context.pos - line.from);

  // Check if inside a comment (# not inside a string)
  let inSingle = false;
  let inDouble = false;
  for (const ch of textBefore) {
    if (ch === "'" && !inDouble) {
      inSingle = !inSingle;
    } else if (ch === '"' && !inSingle) {
      inDouble = !inDouble;
    } else if (ch === "#" && !inSingle && !inDouble) {
      return true;
    }
  }

  return inSingle || inDouble;
}

/**
 * Fallback completion source for R code.
 * Provides keywords, base R functions, constants, tidyverse functions,
 * and control flow snippets. Suppressed inside strings and comments.
 */
export const rCompletionSource: CompletionSource = (
  context: CompletionContext,
) => {
  if (isInsideStringOrComment(context)) {
    return null;
  }
  return completionSource(context);
};
